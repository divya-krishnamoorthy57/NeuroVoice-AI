def sync_seed_data(db):
    """
    Idempotently syncs categories and exercises so that the application has
    all everyday speech training categories and words in English and Tamil.
    Preserves all existing user records, attempts, and sessions.
    """
    # 1. Sync Categories
    category_map = {}
    for cat_data in EVERYDAY_CATEGORIES:
        existing = db.query(ExerciseCategory).filter(ExerciseCategory.slug == cat_data["slug"]).first()
        if not existing:
            cat = ExerciseCategory(**cat_data)
            db.add(cat)
            db.flush()
            category_map[cat.slug] = cat.id
        else:
            category_map[existing.slug] = existing.id

    # 2. Sync English & Tamil Exercises
    all_exercises_to_sync = EVERYDAY_EXERCISES + TAMIL_EXERCISES
    added_count = 0
    updated_count = 0

    for ex_data in all_exercises_to_sync:
        ex_info = dict(ex_data)
        cat_slug = ex_info.pop("category_slug")
        cat_id = category_map.get(cat_slug)
        if not cat_id:
            continue
        ex_info["category_id"] = cat_id
        target_lang = ex_info.get("language", "en-US")

        existing = (
            db.query(Exercise)
            .filter(
                Exercise.target_text == ex_info["target_text"],
                Exercise.category_id == cat_id,
                Exercise.language == target_lang
            )
            .first()
        )

        if not existing:
            ex = Exercise(**ex_info)
            db.add(ex)
            added_count += 1
        else:
            # Safely enrich existing records with example sentences, meanings, images, types
            changed = False
            for field in ["example_sentence", "english_meaning", "translated_sentence", "image_url", "hints", "prompt", "exercise_type"]:
                if ex_info.get(field) and getattr(existing, field) != ex_info[field]:
                    setattr(existing, field, ex_info[field])
                    changed = True
            if changed:
                updated_count += 1

    db.commit()
    logger.info(f"Seeded/Synced exercises: {added_count} added, {updated_count} enriched.")
